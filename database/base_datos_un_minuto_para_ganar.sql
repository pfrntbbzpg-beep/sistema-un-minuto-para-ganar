-- 1. TABLAS
create table cliente (
  id_cliente  int generated by default as identity primary key,
  nombre      varchar(100) not null,
  telefono    varchar(15)  not null
);

create table ubicacion (
  id_ubicacion int generated by default as identity primary key,
  direccion    varchar(150) not null,
  lugar        varchar(100) not null
);

create table evento (
  id_evento     int generated by default as identity primary key,
  id_cliente    int not null references cliente(id_cliente)
                  on delete restrict on update cascade,
  id_ubicacion  int not null references ubicacion(id_ubicacion)
                  on delete restrict on update cascade,
  fecha         date not null,
  hora_inicio   time not null,
  hora_fin      time not null,
  tipo_show     varchar(50) not null,
  num_invitados int not null check (num_invitados >= 1),
  estado        varchar(20) not null default 'pendiente'
                  check (estado in ('pendiente', 'confirmado', 'cancelado')),
  constraint chk_horario check (hora_fin > hora_inicio),
  constraint sin_traslape exclude using gist (
    tsrange(fecha + hora_inicio, fecha + hora_fin) with &&
  ) where (estado <> 'cancelado')
);

create table material (
  id_material         int generated by default as identity primary key,
  nombre              varchar(100) not null,
  tipo                varchar(50)  not null,
  cantidad_disponible int not null check (cantidad_disponible >= 0)
);

create table asignacion_material (
  id_asignacion int generated by default as identity primary key,
  id_evento     int not null references evento(id_evento)
                  on delete restrict on update cascade,
  id_material   int not null references material(id_material)
                  on delete restrict on update cascade,
  cantidad      int not null check (cantidad >= 1)
);

create index idx_evento_cliente   on evento(id_cliente);
create index idx_evento_ubicacion on evento(id_ubicacion);
create index idx_asig_evento      on asignacion_material(id_evento);
create index idx_asig_material    on asignacion_material(id_material);

-- 2. REGLAS DE NEGOCIO
create or replace function validar_disponibilidad()
returns trigger language plpgsql set search_path = public as $$
declare
  disponible int;
begin
  select cantidad_disponible into disponible
  from material where id_material = new.id_material;
  if new.cantidad > disponible then
    raise exception 'Material insuficiente: se piden % y solo hay % disponibles',
      new.cantidad, disponible;
  end if;
  return new;
end;
$$;

create trigger trg_validar_disponibilidad
before insert or update on asignacion_material
for each row execute function validar_disponibilidad();

create or replace function liberar_materiales()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.estado = 'cancelado' and old.estado <> 'cancelado' then
    delete from asignacion_material where id_evento = new.id_evento;
  end if;
  return new;
end;
$$;

create trigger trg_liberar_materiales
after update of estado on evento
for each row execute function liberar_materiales();

