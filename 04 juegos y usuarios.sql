-- ---------------------------------------------------------------------
-- 1. VARIOS ADMINISTRADORES
--    Tabla con los usuarios que pueden usar el sistema.
-- ---------------------------------------------------------------------
create table if not exists administrador (
  id_usuario uuid primary key references auth.users(id) on delete cascade
);
alter table administrador enable row level security;

drop policy if exists "Cada usuario ve su registro" on administrador;
create policy "Cada usuario ve su registro" on administrador
  for select to authenticated using (id_usuario = (select auth.uid()));

-- Da acceso a todos los usuarios que existen ahora en Authentication
insert into administrador (id_usuario)
select id from auth.users
on conflict do nothing;


-- ---------------------------------------------------------------------
-- 2. JUEGOS DEL SHOW
-- ---------------------------------------------------------------------

-- Catálogo de juegos o dinámicas
create table juego (
  id_juego    int generated by default as identity primary key,
  nombre      varchar(100) not null unique,
  descripcion varchar(200)
);

-- Qué materiales necesita cada juego y cuántos
create table juego_material (
  id_juego    int not null references juego(id_juego)
                on delete cascade on update cascade,
  id_material int not null references material(id_material)
                on delete restrict on update cascade,
  cantidad    int not null check (cantidad >= 1),
  primary key (id_juego, id_material)
);

-- Qué juegos se harán en cada evento
create table evento_juego (
  id_evento int not null references evento(id_evento)
              on delete cascade on update cascade,
  id_juego  int not null references juego(id_juego)
              on delete restrict on update cascade,
  primary key (id_evento, id_juego)
);

create index idx_juego_material_material on juego_material(id_material);
create index idx_evento_juego_juego      on evento_juego(id_juego);

